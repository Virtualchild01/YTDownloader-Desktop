'use strict';

const fs = require('node:fs');
const paths = require('./paths');

/**
 * Файл cookies в формате Netscape — единственное, что yt-dlp понимает как «вход в аккаунт».
 *
 * На Android куки вытаскивались из WebView; здесь их отдаёт тот же встроенный Chromium
 * (session.cookies) после входа на accounts.google.com. Формат файла и признаки
 * авторизации повторяют Android-версию один в один, чтобы поведение было одинаковым.
 */

const AUTH_MARKERS = ['LOGIN_INFO', 'SID', 'SSID', 'SAPISID', '__Secure-3PAPISID'];

const YOUTUBE_DOMAIN = '.youtube.com';
const GOOGLE_DOMAIN = '.google.com';
const EXPIRY = '2147483647';

/** Пустой файл или обрывок — не авторизация. */
const MIN_FILE_LENGTH = 50;

/** Домены, с которых Chromium отдаёт куки после логина. */
const COOKIE_URLS = [
  'https://www.youtube.com',
  'https://m.youtube.com',
  'https://youtube.com',
  'https://accounts.google.com',
  'https://www.google.com'
];

function isAuthorized() {
  try {
    const stat = fs.statSync(paths.cookiesPath());
    return stat.isFile() && stat.size > MIN_FILE_LENGTH;
  } catch (e) {
    return false;
  }
}

/** Путь для `--cookies`, если файл есть и непустой. */
function cookiesArg() {
  const file = paths.cookiesPath();
  try {
    return fs.statSync(file).size > 0 ? file : null;
  } catch (e) {
    return null;
  }
}

/** Признаки того, что пользователь действительно вошёл, а не просто открыл страницу. */
function hasAuthMarkers(cookies) {
  const combined = cookies.map((c) => `${c.name}=${c.value}`).join('; ');
  return AUTH_MARKERS.some((marker) => combined.includes(marker));
}

/**
 * Переводит куки Chromium в Netscape-формат.
 * @returns {boolean} true, если нашлись признаки авторизации и файл записан.
 */
function saveFromCookies(cookies) {
  if (!Array.isArray(cookies) || !hasAuthMarkers(cookies)) return false;

  const content = buildCookieFile(cookies);
  const file = paths.cookiesPath();

  // Не переписываем неизменившийся файл: лишняя запись во время активной
  // загрузки отдала бы yt-dlp недописанный файл.
  try {
    if (fs.readFileSync(file, 'utf8') === content) return true;
  } catch (e) {
    // файла ещё нет — просто пишем
  }

  try {
    fs.mkdirSync(paths.cookiesPath().replace(/[\\/][^\\/]+$/, ''), { recursive: true });
    fs.writeFileSync(file, content, 'utf8');
    return true;
  } catch (e) {
    return false;
  }
}

function buildCookieFile(cookies) {
  const lines = ['# Netscape HTTP Cookie File', '# Generated by YTDownloader', ''];

  const added = new Set();
  for (const cookie of cookies) {
    if (!cookie || !cookie.name) continue;
    if (!added.has(cookie.name)) added.add(cookie.name);

    // Как и на Android, кука попадает в оба домена: yt-dlp читает .youtube.com,
    // а Google-куки нужны для проверки возраста и подписки.
    lines.push(netscapeLine(YOUTUBE_DOMAIN, cookie.name, cookie.value));
    lines.push(netscapeLine(GOOGLE_DOMAIN, cookie.name, cookie.value));
  }

  return `${lines.join('\n')}\n`;
}

function netscapeLine(domain, name, value) {
  return `${domain}\tTRUE\t/\tTRUE\t${EXPIRY}\t${name}\t${value == null ? '' : value}`;
}

function clear() {
  try {
    fs.unlinkSync(paths.cookiesPath());
  } catch (e) {
    // файла нет — уже вышли
  }
}

module.exports = {
  COOKIE_URLS,
  isAuthorized,
  cookiesArg,
  hasAuthMarkers,
  saveFromCookies,
  clear
};
